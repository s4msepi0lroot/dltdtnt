def rgb(value, alpha=255):
    return ((value >> 16) & 255, (value >> 8) & 255, value & 255, alpha)


def shade(value, factor):
    r = max(0, min(255, int(((value >> 16) & 255) * factor)))
    gg = max(0, min(255, int(((value >> 8) & 255) * factor)))
    b = max(0, min(255, int((value & 255) * factor)))
    return (r << 16) | (gg << 8) | b


def new_img(size=16):
    return Image.new("RGBA", (size, size), (0, 0, 0, 0))


def rect(px, x0, y0, x1, y1, col):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            px[x, y] = col


def hline(px, x0, x1, y, col):
    for x in range(x0, x1 + 1):
        px[x, y] = col


def vline(px, x, y0, y1, col):
    for y in range(y0, y1 + 1):
        px[x, y] = col


def box(px, x0, y0, x1, y1, col):
    hline(px, x0, x1, y0, col)
    hline(px, x0, x1, y1, col)
    vline(px, x0, y0, y1, col)
    vline(px, x1, y0, y1, col)


def speckle(px, x0, y0, x1, y1, col, chance=0.25):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if random.random() < chance:
                px[x, y] = col


