ordered_drinks = sorted(DRINKS, key=lambda d: CAT_ORDER.index(d["cat"]))

lines = [
    "package com.s4fmer.boozecraft.drink;",
    "",
    "import java.util.Collections;",
    "import java.util.LinkedHashMap;",
    "import java.util.Map;",
    "",
    "import net.minecraft.world.effect.MobEffects;",
    "",
    "/** GENERATED by tools/boozecraft_gen.py - every drink in the mod. */",
    "public final class Drinks {",
    "",
    "\tprivate static final Map<String, DrinkDef> ALL = new LinkedHashMap<>();",
    "",
]
for d in ordered_drinks:
    abv = g(d, "abv", 0.0)
    addiction = round(abv * 10.0, 1)
    call = ["DrinkDef.builder(\"%s\")" % d["id"]]
    call.append(".cat(DrinkCategory.%s)" % d["cat"])
    call.append(".vessel(Vessel.%s)" % d["vessel"])
    call.append(".abv(%.2fD)" % abv)
    if g(d, "nutrition", 0):
        call.append(".nutrition(%d)" % d["nutrition"])
    if addiction:
        call.append(".addiction(%.1fD)" % addiction)
    if g(d, "caffeine", 0):
        call.append(".caffeine(%.1fD)" % float(d["caffeine"]))
    if g(d, "sober", 0):
        call.append(".sober(%.1fD)" % float(d["sober"]))
    if g(d, "relief", 0):
        call.append(".relief(%.1fD)" % float(d["relief"]))
    if g(d, "cure", False):
        call.append(".cure()")
    call.append(".color(0x%06X)" % d["color"])
    for fx in g(d, "fx", []):
        call.append(".fx(MobEffects.%s, %d, %d)" % (fx[0], fx[1], fx[2]))
    call.append(".build()")
    body = ""
    indent = "\t\t\t"
    current = ""
    for part in call:
        if current and len(current) + len(part) > 90:
            body += current + "\n" + indent
            current = ""
        current += part
    body += current
    lines.append("\tpublic static final DrinkDef %s = add(%s);" % (ident(d["id"]), body))
lines += [
    "",
    "\tprivate static DrinkDef add(DrinkDef def) {",
    "\t\tALL.put(def.id(), def);",
    "\t\treturn def;",
    "\t}",
    "",
    "\tpublic static Map<String, DrinkDef> all() {",
    "\t\treturn Collections.unmodifiableMap(ALL);",
    "\t}",
    "",
    "\tpublic static DrinkDef get(String id) {",
    "\t\treturn ALL.get(id);",
    "\t}",
    "",
    "\tprivate Drinks() {",
    "\t}",
    "}",
    "",
]
write(os.path.join(JAVA, "drink/Drinks.java"), "\n".join(lines))

