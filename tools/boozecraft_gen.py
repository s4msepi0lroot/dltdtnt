DRINK_IDS = [d["id"] for d in DRINKS]
TOOL_IDS = [t["id"] for t in TOOLS]
BLOCK_IDS = [b["id"] for b in BLOCKS]
OWN_IDS = set(DRINK_IDS) | set(TOOL_IDS) | set(BLOCK_IDS)
problems = []

if len(DRINK_IDS) != len(set(DRINK_IDS)):
    problems.append("duplicate drink ids")


def check_ref(ref, where):
    if ref.startswith(B):
        if ref[len(B):] not in OWN_IDS:
            problems.append("unknown own item %s in %s" % (ref, where))
    elif not ref.startswith(M):
        problems.append("bad namespace %s in %s" % (ref, where))


for c in CRAFTS:
    check_ref(c["result"], "craft")
    for i in c.get("ingredients", []):
        check_ref(i, "craft " + c["result"])
    for i in c.get("key", {}).values():
        check_ref(i, "craft " + c["result"])
    if "ingredient" in c:
        check_ref(c["ingredient"], "craft " + c["result"])
for p in PROCESS:
    check_ref(p["result"], "process")
    for i in p["inputs"]:
        check_ref(i, "process " + p["result"])
mix_keys = set()
for m in MIX:
    check_ref(m["result"], "mix")
    for i in m["inputs"]:
        check_ref(i, "mix " + m["result"])
    key = "+".join(sorted(m["inputs"]))
    if key in mix_keys:
        problems.append("duplicate mix key " + key)
    mix_keys.add(key)

obtainable = set()
for c in CRAFTS:
    obtainable.add(c["result"])
for p in PROCESS:
    obtainable.add(p["result"])
for m in MIX:
    obtainable.add(m["result"])
for item_id in sorted(OWN_IDS):
    if B + item_id not in obtainable:
        problems.append("no recipe produces " + item_id)

if problems:
    print("VALIDATION PROBLEMS:")
    for p in problems:
        print("  -", p)
    sys.exit(1)
print("validation ok: %d drinks, %d tools, %d blocks, %d crafts, %d machine recipes, %d mixes"
      % (len(DRINKS), len(TOOLS), len(BLOCKS), len(CRAFTS), len(PROCESS), len(MIX)))

